#!/usr/bin/env python3
"""Minimal-syntax report: which constructs the target kernels use, per front end.

    python3 scripts/census/report.py scripts/census/targets.tsv CHECKOUTS \\
        --update documents/census/MinimalSyntax.md

Reads the target manifest, scans every listed file with `scan.py` (the files
are parsed, never imported or run) and prints the report as Markdown. With
`--update FILE` the report replaces everything below the marker line of FILE
instead (`MARKER` below), so the hand-written part above it is kept.

Manifest: tab-separated, `#` starts a comment line. Six columns per row:

    family  front end  repository URL  commit (40 hex digits)  path  note

A row with an empty path names a target that has no file (the note says why)
and is listed, not scanned. A file may appear in several rows (one per family
that names it); it is scanned once.

CHECKOUTS holds one directory per repository and commit, named
`<last component of the URL>@<commit>`, with the repository's tree in it.

A construct is a resolved call name or an `ast` statement class (see `scan.py`
for how names are resolved). A kernel uses a construct when its own body does,
or the body of a function of the same file that it reaches through calls. A
call of such a function is reported as `(local function: <its decorators>)`
instead of by its name. Everything is sorted, so equal inputs give equal bytes.
"""
import argparse
from collections import defaultdict
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from census import scan

MARKER = '<!-- generated by scripts/census/report.py: do not edit below this line -->'
COLUMNS = ('family', 'front_end', 'url', 'commit', 'path', 'note')


def read_manifest(text):
    """Rows of the manifest as dicts; a malformed row ends the run."""
    rows = []
    for number, line in enumerate(text.splitlines(), 1):
        if not line.strip() or line.startswith('#'):
            continue
        fields = line.split('\t')
        if len(fields) != len(COLUMNS):
            raise SystemExit(f'manifest line {number}: {len(fields)} columns, expected {len(COLUMNS)}')
        row = dict(zip(COLUMNS, (f.strip() for f in fields)))
        if row['commit'] and not re.fullmatch('[0-9a-f]{40}', row['commit']):
            raise SystemExit(f'manifest line {number}: commit is not a full hash')
        if row['path'] and not (row['url'] and row['commit']):
            raise SystemExit(f'manifest line {number}: a path needs a repository and a commit')
        if not row['family'] or not row['front_end'] or not (row['path'] or row['note']):
            raise SystemExit(f'manifest line {number}: family, front end and a path or a reason are required')
        rows.append(row)
    return rows


def checkout(row, digits=40):
    return f"{row['url'].rstrip('/').removesuffix('.git').rsplit('/', 1)[-1]}@{row['commit'][:digits]}"


def kernels_of(records):
    """(record, call name -> keywords, statement kinds) per kernel, helpers folded in."""
    by_name = defaultdict(list)
    for r in records:
        by_name[r['function']].append(r)
    for kernel in (r for r in records if r['kernel']):
        reached, todo = [], [kernel]
        while todo:
            r = todo.pop()
            if not any(r is seen for seen in reached):
                reached.append(r)
                todo += [h for name in r['helpers'] for h in by_name[name]]
        calls, statements = defaultdict(set), set()
        for r in reached:
            statements |= set(r['statements'])
            for call in r['calls']:
                name = call['name']
                if name in r['helpers']:
                    decorators = sorted({d for h in by_name[name] for d in h['decorators']})
                    name = f"(local function: {', '.join(decorators) or 'undecorated'})"
                calls[name] |= set(call['kwargs'])
        yield kernel, calls, statements


def ranges(numbers):
    """`1-3, 7` for [1, 2, 3, 7]."""
    out = []
    for n in sorted(numbers):
        if out and out[-1][1] == n - 1:
            out[-1][1] = n
        else:
            out.append([n, n])
    return ', '.join(str(a) if a == b else f'{a}-{b}' for a, b in out)


def cell(text):
    return text.replace('|', '\\|')


def table(header, rows):
    return ['| ' + ' | '.join(header) + ' |', '|' + ' --- |' * len(header),
            *('| ' + ' | '.join(row) + ' |' for row in rows), '']


def report(rows, checkouts):
    """The Markdown report of manifest `rows` over the directory `checkouts`."""
    files = defaultdict(set)  # (front end, repository URL, commit, path) -> families
    for row in rows:
        if row['path']:
            files[row['front_end'], row['url'], row['commit'], row['path']].add(row['family'])
    out = ['## Sources', '']
    pins = defaultdict(set)
    for row in rows:
        if row['commit']:
            pins[row['url'], row['commit']].add(row['path'])
    out += table(['repository', 'commit', 'files scanned'],
                 [[url, f'`{commit}`', str(len(paths - {''}))] for (url, commit), paths in sorted(pins.items())])
    out += ['## Rows without a file', '']
    out += table(['family', 'front end', 'source', 'reason'], sorted(
        [row['family'], row['front_end'], f"`{checkout(row, 12)}`" if row['commit'] else row['url'] or 'none',
         cell(row['note'])] for row in rows if not row['path']))
    for front_end in sorted({key[0] for key in files}):
        legend, calls, statements, keywords = [], defaultdict(set), defaultdict(set), defaultdict(set)
        scanned = sorted(key for key in files if key[0] == front_end)
        for key in scanned:
            source_row = dict(zip(('url', 'commit'), key[1:3]))
            directory, path = checkout(source_row), key[3]
            try:
                source = (Path(checkouts) / directory / path).read_text(encoding='utf-8')
            except OSError as error:
                raise SystemExit(f'{directory}/{path}: {error.strerror}; is the checkout in place?')
            for kernel, its_calls, its_statements in kernels_of(scan.scan_source(source, path)):
                number = len(legend) + 1
                legend.append([str(number), ', '.join(sorted(files[key])), f'`{checkout(source_row, 12)}`',
                               f'`{path}`', f"`{kernel['function']}`", str(kernel['line'])])
                for name, kwargs in its_calls.items():
                    calls[name].add(number)
                    keywords[name] |= kwargs
                for kind in its_statements:
                    statements[kind].add(number)
        out += [f'## {front_end}', '', f'{len(legend)} kernels in {len(scanned)} files.', '']
        if not legend:
            continue
        out += [f'### {front_end}: kernels', '']
        out += table(['#', 'family', 'source', 'file', 'kernel', 'line'], legend)
        out += [f'### {front_end}: calls', '']
        out += table(['call', 'kernels', 'keywords seen', 'used by'], [
            [f'`{name}`', str(len(users)), ' '.join(f'`{k}`' for k in sorted(keywords[name])), ranges(users)]
            for name, users in sorted(calls.items(), key=lambda item: (-len(item[1]), item[0]))])
        out += [f'### {front_end}: statements', '']
        out += table(['statement', 'kernels', 'used by'], [
            [f'`{kind}`', str(len(users)), ranges(users)]
            for kind, users in sorted(statements.items(), key=lambda item: (-len(item[1]), item[0]))])
    return '\n'.join(out)


def main(argv=None):
    parser = argparse.ArgumentParser(description='Print the minimal-syntax report of a target manifest as Markdown.')
    parser.add_argument('manifest')
    parser.add_argument('checkouts', help='directory with one `<repository>@<commit>` checkout per pin')
    parser.add_argument('--update', metavar='FILE', help='replace the text below the marker line of FILE')
    args = parser.parse_args(argv)
    text = report(read_manifest(Path(args.manifest).read_text(encoding='utf-8')), args.checkouts)
    if not args.update:
        print(text, end='')
        return
    document = Path(args.update)
    head, marker, _ = document.read_text(encoding='utf-8').partition(MARKER)
    if not marker:
        raise SystemExit(f'{args.update}: marker line not found')
    document.write_text(f'{head}{MARKER}\n\n{text}', encoding='utf-8')


if __name__ == '__main__':
    main()
