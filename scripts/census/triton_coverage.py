def main(argv=None):
    parser = argparse.ArgumentParser(description='Print the Triton coverage matrix as a Markdown section.')
    parser.add_argument('manifest')
    parser.add_argument('checkouts', help='directory with one `<repository>@<commit>` checkout per pin')
    parser.add_argument('--root', default=Path(__file__).resolve().parents[2], help='repository holding the macro')
    parser.add_argument('--update', metavar='FILE', help='replace the section between the marker lines of FILE')
    args = parser.parse_args(argv)
    text = matrix(report.read_manifest(Path(args.manifest).read_text(encoding='utf-8')), args.checkouts, args.root)
    if not args.update:
        print(text)
        return
    document = Path(args.update)
    head, begin, rest = document.read_text(encoding='utf-8').partition(BEGIN)
    _, end, tail = rest.partition(END)
    if begin and not end:
        raise SystemExit(f'{args.update}: begin marker without end marker')
    document.write_text(f'{head if begin else head.rstrip(chr(10)) + chr(10) * 2}{text}{tail or chr(10)}',
                        encoding='utf-8')


if __name__ == '__main__':
    main()
