#!/usr/bin/env python3
"""Coverage matrix: the Triton 3.5.1 language surface against the `triton { }` macro.

    python3 scripts/census/triton_coverage.py scripts/census/targets.tsv CHECKOUTS \\
        --update documents/TritonSubset.md

Prints one Markdown section. With `--update FILE` the section replaces the text
between the marker lines `BEGIN` and `END` of FILE, or is appended when FILE
has no markers. Equal inputs give equal bytes.

Inputs, all read as data (Python is parsed with `ast`, Lean is read as text;
nothing is imported or run):

    manifest     the target manifest of `report.py`
    CHECKOUTS    as for `report.py`: one `<repository>@<commit>` directory per pin
                 of the manifest, plus `TRITON` and, optionally, `BENCH` below
                 (without the benchmark directory its column says "not counted")
    --root DIR   the repository whose `VeriTile/Triton/DSL/` holds the macro
                 (default: the repository of this script)

Rows: every name of `triton.language.__all__` (`api`), one sub-row per optional
parameter of its signature and per keyword the scanned kernels pass, and the
statement kinds and other calls that `scan.py` reports for those kernels.

How a row is decided. `rules` reads every `syntax` declaration under the
macro's directory and writes it as a form: the atoms as written, `<name>` for a
non-terminal, `«»` for the grouping parentheses of the grammar. A construct has
a rule when a form of the categories `MAIN` spells it:

    call           `tl.name(`             bare name   `tl.name` not followed by `(` or `.`
    keyword `k`    `k=` in a form of the call. Where the form only has a keyword
                   position (`<ident>=`, or a category named `...Kwarg` that has
                   `<ident>=` or `k=`), the syntax takes the keyword and the
                   expander decides: if no file mentions the word `k`, nothing can
                   recognise it (no rule); otherwise the answer is in `READ` or
                   is "not determined"
    statement      the patterns of `STATEMENTS`, over the `tritonStmt` forms
    failure marker a call that the expander lowers to `effectMarker "tl.name"`

`READ` holds what was decided by reading the expander, each entry with the
file, line and a text that line must still contain; when it does not, the row
becomes "not determined". The generated section states where these decisions
can be wrong.
"""
