    ('bf16', [257], {'class': 'special', 'seed': 4}, 'f17392b19b16ee907ca50f11479115b8d818f443aea64e7679668b8cf50f7178'),
    ('fp16', [64], {'class': 'normal', 'seed': 5}, '169333a1bc23c99e13c4c282fb045cdedd5c6bb46ea51f2af2212944d8ec0f89'),
    ('fp64', [], {'class': 'normal', 'seed': 6}, '25d1aa3e427b2b8f287a635ae150858a9f8e12d601567c5fa4f7af3a788010ea'),
