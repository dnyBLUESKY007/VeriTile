class TensorFile(unittest.TestCase):
    def test_every_dtype_round_trips_bit_for_bit(self):
        with tempfile.TemporaryDirectory() as temp:
            for dtype, (_, w) in tensorfile.DTYPES.items():
                data = bytes([1, 0, 1, 1, 0, 0]) if dtype == 'bool' else bytes(range(1, 6 * w + 1))
                tensor = Tensor(dtype, (2, 3), data)
                path = Path(temp) / f'{dtype}.tensor'
                digest = tensorfile.write(path, tensor)
                self.assertEqual(tensorfile.read(path, sha256=digest), tensor)
                self.assertEqual(path.stat().st_size, 16 + 8 * 2 + 6 * w)

    def test_header_bytes_are_as_documented(self):
        raw = Tensor('fp32', (2,), struct.pack('<2f', 1.0, -0.0)).to_bytes()
        self.assertEqual(raw, b'VTTENSR1' + bytes([1, 1]) + bytes(6) + (2).to_bytes(8, 'little')
                         + bytes.fromhex('0000803f' '00000080'))
        scalar = Tensor('int8', (), b'\xff')
        self.assertEqual(tensorfile.from_bytes(scalar.to_bytes()), scalar)

    def test_malformed_files_are_rejected(self):
        good = Tensor('int16', (3,), bytes(6)).to_bytes()
        bad = {
            'magic': b'VTTENSR2' + good[8:],
            'dtype code': good[:8] + bytes([7]) + good[9:],
            'rank': good[:9] + bytes([9]) + good[10:],
            'reserved byte': good[:12] + b'\x01' + good[13:],
            'short data': good[:-1],
            'long data': good + b'\x00',
            'bool value': Tensor('uint8', (1,), b'\x02').to_bytes()[:8] + bytes([32]) + Tensor('uint8', (1,), b'\x02').to_bytes()[9:],
        }
        for name, raw in bad.items():
            with self.subTest(name), self.assertRaises(TensorFormatError):
                tensorfile.from_bytes(raw)

    def test_wrong_sha256_is_rejected(self):
        with tempfile.TemporaryDirectory() as temp:
            path = Path(temp) / 'x.tensor'
            tensorfile.write(path, Tensor('uint8', (1,), b'\x05'))
            with self.assertRaises(TensorFormatError):
                tensorfile.read(path, sha256='0' * 64)

    def test_sentinel_fill_and_write_footprint(self):
        buffer = tensorfile.filled('fp32', (4,))
        self.assertEqual(buffer.data, bytes.fromhex('addec07f') * 4)
        written = Tensor('fp32', (4,), buffer.data[:4] + struct.pack('<f', 2.5) + buffer.data[8:])
        self.assertEqual(tensorfile.written_mask(written), [False, True, False, False])
        self.assertEqual(tensorfile.filled('int16', (1,), '0x1234').data, b'\x34\x12')
        for wrong in ('0x12', '1234', '0x12345', '0x1_23', '0x12g4'):
            with self.subTest(wrong), self.assertRaises(TensorFormatError):
                tensorfile.sentinel_bytes('int16', wrong)
        with self.assertRaises(TensorFormatError):
            tensorfile.filled('bool', (1,))


class Generator(unittest.TestCase):
    def test_golden_hashes(self):
        for dtype, shape, gen, digest in GOLDEN:
            with self.subTest(dtype=dtype, gen=gen):
                self.assertEqual(gen_inputs.generate(dtype, shape, gen).sha256(), digest)

    def test_seed_class_and_shape_select_the_stream(self):
        base = gen_inputs.generate('fp32', [64], {'class': 'normal', 'seed': 1})
        self.assertEqual(base, gen_inputs.generate('fp32', [64], {'class': 'normal', 'seed': 1}))
        for other in (gen_inputs.generate('fp32', [64], {'class': 'normal', 'seed': 2}),
                      gen_inputs.generate('fp32', [64], {'class': 'boundary', 'seed': 1}),
                      gen_inputs.generate('fp32', [8, 8], {'class': 'normal', 'seed': 1})):
            self.assertNotEqual(base.data, other.data)

    def test_normal_values_look_standard_normal(self):
        values = struct.unpack('<4096f', gen_inputs.generate('fp32', [4096], {'class': 'normal', 'seed': 1}).data)
        mean = sum(values) / len(values)
        variance = sum((v - mean) ** 2 for v in values) / len(values)
        self.assertLess(abs(mean), 0.1)
        self.assertTrue(0.9 < variance < 1.1, variance)
        self.assertTrue(all(-6 <= v < 6 for v in values))

    def test_special_floats_cover_the_special_values_and_avoid_sentinels(self):
        for dtype in gen_inputs.FLOATS:
            tensor = gen_inputs.generate(dtype, [2000], {'class': 'special', 'seed': 3})
            elements = {tensor.element(i) for i in range(2000)}
            for special in gen_inputs.float_specials(dtype):
                self.assertIn(special, elements, (dtype, special.hex()))
            self.assertNotIn(tensorfile.sentinel_bytes(dtype), elements)
        nan = gen_inputs.float_specials('fp32')[4]
        self.assertEqual(nan, bytes.fromhex('0000c07f'))

    def test_integers_stay_in_range_and_avoid_the_sentinel(self):
        tensor = gen_inputs.generate('int64', [500], {'class': 'normal', 'seed': 8, 'low': 0, 'high': 49999})
        self.assertTrue(all(0 <= v <= 49999 for v in struct.unpack('<500q', tensor.data)))
        for dtype in ('int8', 'int16', 'int32', 'int64', 'uint8', 'uint16', 'uint32', 'uint64'):
            tensor = gen_inputs.generate(dtype, [400], {'class': 'special', 'seed': 7})
            self.assertTrue(all(tensorfile.written_mask(tensor)), dtype)
        with self.assertRaises(ValueError):
            gen_inputs.generate('int8', [1], {'class': 'normal', 'seed': 1, 'high': 1000})

    def test_unknown_class_and_fp8_are_refused(self):
        with self.assertRaises(ValueError):
            gen_inputs.generate('fp32', [1], {'class': 'uniform', 'seed': 1})
        with self.assertRaises(NotImplementedError):
            gen_inputs.generate('f8e4', [1], {'class': 'normal', 'seed': 1})


if __name__ == '__main__':
    unittest.main()
